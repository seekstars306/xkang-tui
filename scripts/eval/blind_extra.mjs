import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const dir = fs.readdirSync('eval_run').find(d => d.startsWith('batch-cmpre-gemini-images-'));
const rec = JSON.parse(fs.readFileSync(path.join('eval_run', dir, 'T004.json'), 'utf8'));
const a = rec.answer;
const parts = ['【结论】' + (a.conclusion || '')];
if (a.businessData?.length) parts.push('【业务数据】\n' + a.businessData.map(d => '- ' + d.label + '：' + d.value).join('\n'));
if (a.evidenceSummary?.length) parts.push('【依据摘要】\n' + a.evidenceSummary.map(s => '- ' + s).join('\n'));
if (a.customerReply) parts.push('【客服话术】' + a.customerReply);
if (a.pendingItems?.length) parts.push('【待确认事项】\n' + a.pendingItems.map(s => '- ' + s).join('\n'));
const blindId = 'X' + crypto.randomBytes(3).toString('hex');
fs.writeFileSync('eval_run/blind-20261029/pack-extra.json', JSON.stringify({ answers: [{ blindId, ticket: 'T004', answer: parts.join('\n\n') }] }, null, 2));
const keyPath = 'eval_run/blind-20261029-key/key.json';
const key = JSON.parse(fs.readFileSync(keyPath, 'utf8'));
const l3 = (rec.metrics?.llmByModel || []).find(m => String(m.model).includes('[L3]'));
const l2 = (rec.metrics?.llmByModel || []).find(m => String(m.model).includes('[L2]'));
key.push({ blindId, ticket: 'T004', d: dir, model: 'gemini', sw: 'on', rerun: true, reviewStatus: a?.reviewStatus, l3: l3 ? l3.n + '/' + l3.fail + 'fail' : 'none', l2: l2 ? l2.n + '/' + l2.fail + 'fail' : 'none', infraFail: false, minutes: rec.durationMin });
fs.writeFileSync(keyPath, JSON.stringify(key, null, 2));
console.log('extra written', blindId.length);